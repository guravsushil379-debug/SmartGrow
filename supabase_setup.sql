create table if not exists public.inventory_reports (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  username text not null,
  business_name text not null,
  input_data jsonb not null,
  report_data jsonb not null,
  created_at timestamptz not null default now()
);

alter table public.inventory_reports
  add column if not exists input_data jsonb;

create index if not exists inventory_reports_user_created_idx
  on public.inventory_reports (user_id, created_at desc);

alter table public.inventory_reports enable row level security;

drop policy if exists "Users can read their own inventory reports"
  on public.inventory_reports;
create policy "Users can read their own inventory reports"
  on public.inventory_reports
  for select
  to authenticated
  using ((select auth.uid()) = user_id);

drop policy if exists "Users can insert their own inventory reports"
  on public.inventory_reports;
create policy "Users can insert their own inventory reports"
  on public.inventory_reports
  for insert
  to authenticated
  with check ((select auth.uid()) = user_id);
